function parsePaymentString($raw) {
    $s = trim($raw);
    $s = preg_replace('/^(paid on|pain on)\s+/i', '', $s);
    $s = preg_replace('/(\d+)(st|nd|rd|th)/i', '$1', $s);
    $s = str_ireplace(['Sept.', 'Sept'], 'Sep', $s);
    $s = str_ireplace(['July.'], 'Jul', $s);
    $s = str_ireplace(['Oct.'], 'Oct', $s);
    $s = trim($s, '. ');

    // Handle "paid on june 2026"
    if (preg_match('/^june\s+2026$/i', $s)) {
        return '2026-06-01';
    }

    // Check if format is "Month Day, Time" like "Jul 13, 11:39 AM"
    // Wait, are these from 2025 or 2026?
    // Notice 84 is Mar 19, 2025, 89 is Dec 18, 2024.
    // If Jul 13 follows Sept 2026, could it be 2025 or 2026?
    if (preg_match('/^([a-z]{3})\s+(\d{1,2}),?\s*(\d{1,2}:\d{2}\s*(?:AM|PM))?$/i', $s, $m)) {
        // e.g. Jul 13
        $mon = $m[1];
        $day = $m[2];
        $time = $m[3] ?? '00:00:00';
        // Let's use 2025 or 2026 - if 2026:
        $s = "$day $mon 2025 $time";
    }

    $ts = strtotime($s);
    if ($ts) {
        return date('Y-m-d', $ts);
    }
    return 'FAILED: ' . $s;
}

